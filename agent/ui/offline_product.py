def _action(action: str, args: dict[str, Any] | None = None) -> str:
    return json.dumps({"type": "action", "action": action, "args": args or {}}, ensure_ascii=False)


def _write(path: str, content: str) -> str:
    return _action("write_file", {"path": path, "content": content})


def _verify_command(required_paths: list[str]) -> str:
    script = (
        "from pathlib import Path; "
        f"required={required_paths!r}; "
        "missing=[p for p in required if not Path(p).exists()]; "
        "assert not missing, missing; "
        "print('offline scaffold ok')"
    )
    return _action("run_command", {"command": f'"{sys.executable}" -c "{script}"', "timeout": 30.0})


def _is_spring_vue_goal(goal: str) -> bool:
    lower = goal.lower()
    management_tokens = (
        "管理系统",
        "管理后台",
        "人员管理",
        "员工管理",
        "增删改查",
        "毕业设计",
        "crud",
        "admin",
        "dashboard",
    )
    return (
        ("spring" in lower and "vue" in lower)
        or "spring boot" in lower
        or "前后端" in goal
        or any(token in lower or token in goal for token in management_tokens)
    )


