class OfflineProductBrain(AgentBrain):
    """Deterministic UI-only offline generator; keeps product testing useful without API quota."""

    def __init__(self, workspace: Path) -> None:
        self.workspace = workspace
        self._actions: list[str] | None = None
        self._index = 0

    def _ensure_actions(self, goal: str) -> None:
        if self._actions is not None:
            return
        self._actions = _spring_vue_actions(goal) if _is_spring_vue_goal(goal) else _flask_product_actions(goal)

    def decide(
        self,
        goal: str,
        plan: dict[str, Any],
        state: ProjectState,
        last_result: dict[str, Any] | None,
        session: SessionMemory | None = None,
    ) -> str:
        _ = plan, state, last_result, session
        self._ensure_actions(goal)
        actions = self._actions or [_action("finish", {"reason": "offline product brain had no actions"})]
        if self._index >= len(actions):
            return _action("finish", {"reason": "offline product prototype complete"})
        line = actions[self._index]
        self._index += 1
        return line
